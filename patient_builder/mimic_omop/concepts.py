def diagnosis_vocabulary(icd_version: int) -> str:
    if icd_version == 9:
        return "ICD9CM"
    if icd_version == 10:
        return "ICD10CM"
    return f"ICD{icd_version}"


def procedure_vocabulary(icd_version: int) -> str:
    if icd_version == 9:
        return "ICD9Proc"
    if icd_version == 10:
        return "ICD10PCS"
    return f"ICD{icd_version}Proc"
